const assert = require('node:assert/strict');
const {emailEntry} = require('../browser/workday.cjs');
const page = {url:'https://example.wd5.myworkdayjobs.com/en-US/Careers/job/Example-City/Engineer_JR123/apply/applyManually',fields:[],text:'Create Account/Sign In'};
const button = {text:'Sign in with email',form_id:null,form_action:''};
assert.equal(emailEntry(page,button),true);
for(const changed of [{...page,fields:[{type:'password'}]}, {...page,url:page.url.replace('myworkdayjobs.com','example.com')}, {...page,text:'Submit application'}]) assert.equal(emailEntry(changed,button),false);
assert.equal(emailEntry(page,{...button,form_action:page.url}),false);
console.log('Workday email chooser stays scoped to an empty credential-entry screen.');
const {accountEntry} = require('../browser/workday.cjs');
const signIn = {...page,text: "Create Account/Sign In Don't have an account yet?", fields:[{type:'password'}]};
assert.equal(accountEntry(signIn,{...button,text:'Create Account'}),true);
assert.equal(accountEntry(signIn,{...button,text:'Create Account',form_id:'signup'}),false);
assert.equal(accountEntry({...signIn,fields:[{type:'password'},{type:'password'}]},{...button,text:'Create Account'}),false);
