"""Document provenance and real rendering checks, using temporary private files."""

from io import BytesIO
from pathlib import Path
import tempfile
import unittest
from zipfile import ZipFile

from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt
from reportlab.pdfgen import canvas

from applydesk.document_import import read_docx, replace_docx, validate_upload
from applydesk.documents import DocumentService


def sample_docx():
    # This synthetic fixture includes table and header text missed by simple readers.
    document = Document()
    section = document.sections[0]
    section.top_margin = section.bottom_margin = Inches(0.65)
    document.styles["Normal"].font.name = "Arial"
    document.styles["Normal"].font.size = Pt(10)
    section.header.paragraphs[0].text = "SAMPLE PROFILE"
    document.add_heading("Alex Sample", 0)
    document.add_paragraph("alex@example.test | San Francisco")
    document.add_heading("Experience", 1)
    paragraph = document.add_paragraph("Software intern\t2025")
    paragraph.add_run("\nBuilt a tested scheduling tool.")
    table = document.add_table(rows=1, cols=2)
    table.cell(0, 0).text = "Education"
    table.cell(0, 1).text = "Example University"
    stream = BytesIO()
    document.save(stream)
    return stream.getvalue()


def sample_pdf():
    # A simple text PDF is enough to exercise explicit reconstruction confirmation.
    stream = BytesIO()
    page = canvas.Canvas(stream)
    page.setFont("Helvetica-Bold", 20)
    page.drawString(48, 780, "Alex Sample")
    page.setFont("Helvetica", 11)
    page.drawString(48, 750, "Software engineering student")
    page.drawString(48, 725, "Built a scheduling tool with Python")
    page.save()
    return stream.getvalue()


class DocumentTests(unittest.TestCase):
    def setUp(self):
        # Each service has a private root and no real user documents.
        self.temporary = tempfile.TemporaryDirectory(prefix="applydesk-doc-test-")
        self.service = DocumentService(Path(self.temporary.name))

    def tearDown(self):
        # Do not retain synthetic identity information in the application workspace.
        self.temporary.cleanup()

    def test_filename_and_package_validation(self):
        # Upload validation happens before any renderer touches untrusted files.
        for filename, data in (("../resume.pdf", b"%PDF-test"), ("fake.docx", b"wrong"),
                               ("resume.txt", b"text"), ("empty.pdf", b"")):
            with self.subTest(filename=filename), self.assertRaises(ValueError):
                validate_upload(filename, data)

    def test_edit_preserves_unchanged_inline_styles(self):
        # Expanding a skill list must not spread its bold label into the new content.
        document = Document()
        paragraph = document.add_paragraph()
        paragraph.add_run("Skills: ").bold = True
        paragraph.add_run("Python").bold = False
        source = Path(self.temporary.name) / "inline.docx"
        output = Path(self.temporary.name) / "edited.docx"
        document.save(source)
        replace_docx(source, output, {"word/document.xml#p0": "Skills: Python and SQL"})
        edited = Document(output).paragraphs[0]
        self.assertEqual(edited.text, "Skills: Python and SQL")
        self.assertTrue(edited.runs[0].bold)
        self.assertFalse(edited.runs[1].bold)

    def test_word_fields_cannot_be_overwritten(self):
        # Field display text can be regenerated by Word, so it is never an editable fact.
        document = Document()
        paragraph = document.add_paragraph()
        field = OxmlElement("w:fldChar")
        field.set(qn("w:fldCharType"), "begin")
        paragraph.add_run()._r.append(field)
        paragraph.add_run("2026")
        document.add_paragraph("A field continues across paragraphs")
        source = Path(self.temporary.name) / "field.docx"
        document.save(source)
        block = read_docx(source)["blocks"][0]
        self.assertTrue(block["uneditable"])
        self.assertTrue(read_docx(source)["blocks"][1]["uneditable"])
        with self.assertRaisesRegex(ValueError, "Word fields"):
            replace_docx(source, source.with_name("changed.docx"), {block["id"]: "2027"})

    def test_docx_versions_preserve_package_and_source(self):
        # A rendered version must contain the edited text and retain unrelated parts.
        data = sample_docx()
        template = self.service.import_file("resume.docx", data, "resume_template")
        self.assertTrue(any(block["text"] == "Education" for block in template["blocks"]))
        self.assertTrue(any(block["text"] == "SAMPLE PROFILE" for block in template["blocks"]))
        block = next(block for block in template["blocks"] if block["text"].startswith("Software intern"))
        version = self.service.create(template["id"], {block["id"]: "Software intern\t2025\nTested a scheduling tool."}, "Engineering", "Engineering")
        edited = self.service.edit(version["id"], {block["id"]: "Software intern\t2025\nAdded regression tests."})
        self.assertNotEqual(version["id"], edited["id"])
        self.assertNotEqual(version["sha256"], edited["sha256"])
        self.assertEqual(self.service.asset(template["source_path"]).read_bytes(), data)
        self.assertIn("Tested a scheduling tool.", self.service.get(version["id"])["text"])
        self.assertEqual(edited["parent_id"], version["id"])
        self.assertEqual(len(edited["image_paths"]), 1)
        job_copy = self.service.copy_for_job(edited["id"], "job-example")
        self.assertEqual(job_copy["job_id"], "job-example")
        self.assertEqual(job_copy["sha256"], edited["sha256"])
        self.assertIsNone(self.service.get(edited["id"])["job_id"])
        self.assertTrue(self.service.verify(job_copy["id"]))
        self.service.asset(job_copy["pdf_path"]).write_bytes(b"tampered")
        with self.assertRaisesRegex(ValueError, "changed outside"):
            self.service.verify(job_copy["id"])
        with ZipFile(BytesIO(data)) as original, ZipFile(self.service.asset(edited["docx_path"])) as result:
            self.assertEqual(original.namelist(), result.namelist())
            for part in original.namelist():
                if part != "word/document.xml":
                    self.assertEqual(original.read(part), result.read(part), part)

    def test_pdf_template_requires_fidelity_confirmation(self):
        # Merely importing a PDF must never make its reconstructed layout approved.
        template = self.service.import_file("resume.pdf", sample_pdf(), "resume_template")
        self.assertTrue(template["needs_fidelity_confirmation"])
        self.assertTrue(template["source_image_paths"])
        with self.assertRaisesRegex(ValueError, "Confirm"):
            self.service.create(template["id"], {}, "Engineering")
        self.service.confirm_template(template["id"])
        version = self.service.create(template["id"], {}, "Engineering")
        self.assertIn("Alex Sample", version["text"])
        self.assertTrue(self.service.asset(version["pdf_path"]).is_file())

    def test_unknown_edits_and_asset_escape_are_rejected(self):
        # Reordered or missing field identifiers cannot accidentally target another block.
        template = self.service.import_file("resume.docx", sample_docx(), "resume_template")
        with self.assertRaisesRegex(ValueError, "no longer exists"):
            self.service.create(template["id"], {"wrong-block": "Replacement"}, "Engineering")
        with self.assertRaises(ValueError):
            self.service.asset("../../../../etc/passwd")
        self.assertEqual(len(self.service.list_documents()), 0)
        self.service.asset(template["source_path"]).write_bytes(b"tampered")
        with self.assertRaisesRegex(ValueError, "template changed"):
            self.service.create(template["id"], {}, "Engineering")


if __name__ == "__main__":
    unittest.main()
